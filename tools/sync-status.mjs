/**
 * 给 STATUS.md 顶部加一段「当前状态」。
 *
 * 为什么加在最前面而不是改那些旧表格：STATUS.md 是接手时的第一份读物，
 * 而它的进度表停在好几轮之前（还把「离线」「曲面」列在待办里，其实早做完了）。
 * 逐行改那几十行旧表格既费事又容易改错；**在最前面写清「现在到哪了、以谁为准」**
 * 更省、也更容易保持新鲜 —— 后来的人一眼就看到真相，不会照着旧表白做一轮。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const file = 'STATUS.md'
if (!existsSync(file)) {
  console.error('没有 STATUS.md')
  process.exit(1)
}
const t = readFileSync(file, 'utf8')
if (t.includes('## 当前状态（最新，以此为准）')) {
  console.log('已经加过了，不重复加')
  process.exit(0)
}

const header = `## 当前状态（最新，以此为准）

> **下面那些按轮次写的进度表停在好几轮之前**（还把「离线」「曲面立体」「导出」列在待办里，
> 其实都已经做完并提交了）。**以这一节为准**，旧表格只当历史记录看。

- **当前版本**：\`1.0.0-my.17\`（分支 \`my-version\`）
- **另一条分支**：\`original\`（标签 \`v1.0-original\`）—— 用户看惯的那一版，两条共同保留，
  \`git checkout original\` 可以切回去对比
- **自检**：**15 项 node 自检 + \`tsc --noEmit\`**（\`pnpm check\`），必须全绿才算这一轮做完

### 已经做完的（旧表格里可能还写着「未开始」）

- 三种解题法（向量法 / 坐标系法 / 基底法）、按「问」分组、步骤播放器
- 面配色与点面显隐、角度三档、长度标注、向量箭头、面法向量、孤立点
- **坐标轴 + 坐标标注 + 三个坐标平面的网格**（格子恒为 1 个长度单位、右手系）
- **曲面立体**（球 / 椭球 / 圆柱 / 圆锥 / 圆台）+ 端面圆 + **整块开合**
- 三种动点（棱上滑 / 面内滑 / 绕棱旋转）与拖动联动
- 导出图片（**带题面**）、录制解题动画视频、\`.g3d\` 打包与导入
- 历史存档（10 条上限 + 按题面去重）、**原图与解答都存**
- **离线**（service worker）与 **HTTPS**（\`pnpm cert\` 自签证书）

### 还没做的

- **打包 APK（Capacitor，安卓 14+）与电脑 exe（Electron）** —— 用户明确要求**放最后**
- 「一键跳手机文件管理器」—— 网页做不到，要等 APK
- 球面动点 —— 用户明确取消
- 审计留下的 20 余条中等项（最要紧三条：\`unit()\` 退化时伪造方向、
  \`edgeKey\`/\`faceKey\` 顺序敏感、上屏门槛缺退化检查）

### 接手时先读

1. **\`核查表.md\`** —— 逐项列「功能 / 你怎么验 / 我验过没有 / 已知问题」，是给用户核对的
2. 本节（当前状态）
3. \`CHANGELOG.md\` 里 \`1.0.0-my.14\` 那一条 —— 把断掉的十几个提交一次说清了

---

`

writeFileSync(file, header + t)
console.log('已在 STATUS.md 顶部加入「当前状态」一节')
